<#
.SYNOPSIS
    Publishes a GitHub release of GitGui, acting as the GitHub user you choose.

.DESCRIPTION
    Uses the GitHub CLI (gh). Steps:
      1. checks gh is installed and signed in, and switches to -GitHubUser (gh auth switch) when given;
      2. checks that you are on main, with a clean working tree, and that main is pushed to origin;
      3. bumps the version in pom.xml (patch by default, see -Bump) and derives the tag v<version>;
      4. builds with package.ps1 (jar + app image, plus the .msi with -Msi) and zips the app image;
         if the build fails, pom.xml is restored and nothing is committed;
      5. writes SHA-256 checksums and asks for confirmation;
      6. commits the bump on main in a dedicated commit ("Release <version>") and pushes main;
      7. creates the tag on that commit and the release with "gh release create", uploading the files.

    The push and the release are done by the chosen GitHub account, so that account needs write
    access to the repository. Nothing leaves your machine before the confirmation (use -Yes to skip
    it). With -DryRun the script builds with the bumped version, then restores pom.xml and stops:
    no commit, no push, no release.

    The GitHub user is never stored in the repository: pass -GitHubUser, or set the GITGUI_GH_USER
    environment variable, or leave both empty to use the account gh is currently using.

.PARAMETER GitHubUser
    GitHub login to release with. Default: $env:GITGUI_GH_USER, otherwise the active gh account.

.PARAMETER Bump
    Which part of the version to increase: patch (default), minor, major, or none to release the
    version currently in pom.xml without creating a bump commit. A -SNAPSHOT suffix is dropped.

.PARAMETER Repo
    Target repository as owner/name. Default: taken from the "origin" remote.

.PARAMETER Notes
    Release notes text. Default: notes generated by GitHub from the merged pull requests and commits.

.PARAMETER Msi
    Also builds and attaches the Windows installer (needs the WiX Toolset).

.PARAMETER Icon
    Optional .ico file passed to package.ps1.

.PARAMETER Draft
    Creates the release as a draft, to review it on GitHub before publishing.

.PARAMETER Prerelease
    Marks the release as a pre-release.

.PARAMETER SkipTests
    Builds without running the tests.

.PARAMETER MavenPath
    Path to mvn.cmd or to the Maven installation folder.

.PARAMETER Yes
    Does not ask for confirmation before publishing.

.PARAMETER DryRun
    Builds and checks everything but does not create the tag or the release.

.EXAMPLE
    .\scripts\release.ps1 -GitHubUser my-login
    .\scripts\release.ps1 -GitHubUser my-login -Draft -Msi
    .\scripts\release.ps1 -DryRun
#>
[CmdletBinding()]
param(
    [string]$GitHubUser,
    [ValidateSet('patch', 'minor', 'major', 'none')]
    [string]$Bump = 'patch',
    [string]$Repo,
    [string]$Notes,
    [switch]$Msi,
    [string]$Icon,
    [switch]$Draft,
    [switch]$Prerelease,
    [switch]$SkipTests,
    [string]$MavenPath,
    [switch]$Yes,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$LogTag = 'release'
. (Join-Path $PSScriptRoot 'toolchain.ps1')

function Stop-Release($msg) { Write-Warn $msg; exit 1 }

function Invoke-Gh([string[]]$GhArgs) {
    # Runs gh, returns its output as a string and stops the script when gh fails.
    $out = & gh @GhArgs
    if ($LASTEXITCODE -ne 0) { Stop-Release "gh $($GhArgs -join ' ') failed (exit $LASTEXITCODE)." }
    return ($out | Out-String).Trim()
}

function Test-Native([scriptblock]$Block) {
    # True when the native command succeeds; its output is discarded.
    $prev = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try { & $Block *> $null; return ($LASTEXITCODE -eq 0) } finally { $ErrorActionPreference = $prev }
}

# ---------------------------------------------------------------- GitHub CLI and account

if (-not (Get-Command gh -CommandType Application -ErrorAction SilentlyContinue)) {
    Write-Warn 'The GitHub CLI (gh) was not found. Install it with: winget install GitHub.cli'
    exit 1
}
if (-not (Get-Command git -CommandType Application -ErrorAction SilentlyContinue)) { Stop-Release 'git was not found on the PATH.' }

if (-not $GitHubUser) { $GitHubUser = $env:GITGUI_GH_USER }

if (-not (Test-Native { gh auth status --hostname github.com })) {
    Stop-Release 'gh is not signed in to github.com. Run: gh auth login'
}
$activeUser = Invoke-Gh @('api', 'user', '--jq', '.login')
if ($GitHubUser -and $activeUser -ne $GitHubUser) {
    # Only switch when needed: "gh auth switch" fails when the account is already the active one.
    if (-not (Test-Native { gh auth switch --hostname github.com --user $GitHubUser })) {
        Stop-Release "Could not switch gh to '$GitHubUser'. Sign in with that account first: gh auth login"
    }
    $activeUser = Invoke-Gh @('api', 'user', '--jq', '.login')
    if ($activeUser -ne $GitHubUser) { Stop-Release "gh is using '$activeUser' instead of '$GitHubUser'." }
}
Write-Info "GitHub account: $activeUser"

# git authenticates with the gh account chosen above, whatever login the origin remote URL carries.
function Invoke-GitAs([string[]]$GitArgs) {
    & git -C $ProjectDir -c credential.helper= -c 'credential.helper=!gh auth git-credential' @GitArgs
}

# ---------------------------------------------------------------- repository

Push-Location $ProjectDir
try {
    if (-not $Repo) {
        $origin = (& git remote get-url origin | Out-String).Trim()
        # The remote URL may embed a login (https://user@github.com/...): only owner/name is kept.
        if ($origin -match 'github\.com[:/]+([^/]+)/([^/]+?)(?:\.git)?/?$') { $Repo = "$($Matches[1])/$($Matches[2])" }
        else { Stop-Release "Could not read owner/name from the origin remote ($origin). Pass -Repo owner/name." }
    }
    Write-Info "Repository: $Repo"

    $branch = (& git branch --show-current | Out-String).Trim()
    if ($branch -ne 'main') { Stop-Release "Releases are made from main, but the current branch is '$branch'." }
    if (& git status --porcelain) { Stop-Release 'The working tree has uncommitted changes. Commit or discard them first.' }

    $head = (& git rev-parse HEAD | Out-String).Trim()
    $remoteMain = ((Invoke-GitAs @('ls-remote', "https://github.com/$Repo.git", 'refs/heads/main') | Out-String).Trim() -split '\s+')[0]
    if ($LASTEXITCODE -ne 0 -or -not $remoteMain) { Stop-Release "Could not read main from $Repo (no access, or the repository does not exist)." }
    if ($remoteMain -ne $head) {
        Stop-Release "main is not in sync with $Repo (local $($head.Substring(0, 7)), remote $($remoteMain.Substring(0, 7))). Push or pull it first."
    }

    # A failing CI on this commit is worth knowing about before releasing it (a warning, not a stop).
    $runs = $null
    try { $runs = & gh run list --repo $Repo --commit $head --limit 5 --json status,conclusion 2>$null | ConvertFrom-Json } catch { }
    if (-not $runs) { Write-Warn 'No CI run found for this commit.' }
    elseif ($runs | Where-Object { $_.conclusion -in @('failure', 'cancelled', 'timed_out') }) { Write-Warn 'CI failed on this commit.' }
    elseif ($runs | Where-Object { $_.status -ne 'completed' }) { Write-Warn 'CI is still running on this commit.' }
} finally {
    Pop-Location
}

# ---------------------------------------------------------------- version and tag

$pomPath = Join-Path $ProjectDir 'pom.xml'
$pomBytes = [IO.File]::ReadAllBytes($pomPath)
$pomBom = ($pomBytes.Length -ge 3 -and $pomBytes[0] -eq 0xEF -and $pomBytes[1] -eq 0xBB -and $pomBytes[2] -eq 0xBF)
$pomText = [IO.File]::ReadAllText($pomPath)   # strips the BOM; it is written back below when there was one
$versionPattern = '(<artifactId>gitgui</artifactId>\s*<version>)([^<]+)(</version>)'
if ($pomText -notmatch $versionPattern) { Stop-Release 'Could not find the project <version> in pom.xml.' }
$currentVersion = $Matches[2]
if ($currentVersion -notmatch '^(\d+)\.(\d+)\.(\d+)') { Stop-Release "Version '$currentVersion' is not in major.minor.patch form." }
$major = [int]$Matches[1]; $minor = [int]$Matches[2]; $patch = [int]$Matches[3]
switch ($Bump) {
    'patch' { $patch++ }
    'minor' { $minor++; $patch = 0 }
    'major' { $major++; $minor = 0; $patch = 0 }
    'none'  { if ($currentVersion -like '*-SNAPSHOT') { Stop-Release "Version $currentVersion is a SNAPSHOT: use -Bump or set a release version." } }
}
$version = if ($Bump -eq 'none') { $currentVersion } else { "$major.$minor.$patch" }
$tag = "v$version"

if (Test-Native { gh release view $tag --repo $Repo }) { Stop-Release "A release for $tag already exists in $Repo." }
if (& git -C $ProjectDir tag --list $tag) { Stop-Release "The tag $tag already exists locally." }
Write-Info "Version $currentVersion -> $version (tag $tag)"

function Restore-Pom {
    # Puts pom.xml back as committed (the working tree was clean when the script started).
    & git -C $ProjectDir checkout -- pom.xml
}

# ---------------------------------------------------------------- build

$committed = $false
try {
    if ($Bump -ne 'none') {
        $newText = [regex]::Replace($pomText, $versionPattern, ('${1}' + $version + '${3}'))
        [IO.File]::WriteAllText($pomPath, $newText, (New-Object System.Text.UTF8Encoding($pomBom)))
        Write-Step "pom.xml: $currentVersion -> $version"
    }

    $package = Join-Path $PSScriptRoot 'package.ps1'
    $pkgArgs = @{}
    if ($SkipTests) { $pkgArgs.SkipTests = $true }
    if ($MavenPath) { $pkgArgs.MavenPath = $MavenPath }
    if ($Icon) { $pkgArgs.Icon = $Icon }

    $dist = Join-Path $ProjectDir 'target\dist'
    & $package -Type app-image @pkgArgs
    if ($LASTEXITCODE -ne 0) { Stop-Release 'package.ps1 (app-image) failed; pom.xml was restored.' }
    if ($Msi) {
        & $package -Type msi @pkgArgs -SkipTests
        if ($LASTEXITCODE -ne 0) { Stop-Release 'package.ps1 (msi) failed; pom.xml was restored.' }
    }

    $assets = New-Object System.Collections.Generic.List[string]
    $jar = Get-ChildItem -LiteralPath (Join-Path $ProjectDir 'target') -Filter "gitgui-$version-all.jar" -File | Select-Object -First 1
    if (-not $jar) { Stop-Release "The jar gitgui-$version-all.jar was not produced." }
    $assets.Add($jar.FullName)

    $zip = Join-Path $dist "GitGui-$version-windows.zip"
    if (Test-Path -LiteralPath $zip) { Remove-Item -LiteralPath $zip -Force }
    Write-Step "Compressing the app image to $zip"
    # ZipFile (not Compress-Archive): it handles big files and writes portable entry names.
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    [IO.Compression.ZipFile]::CreateFromDirectory((Join-Path $dist 'GitGui'), $zip, [IO.Compression.CompressionLevel]::Optimal, $true)
    $assets.Add($zip)

    if ($Msi) {
        $msiFile = Get-ChildItem -LiteralPath $dist -Filter "GitGui-$version.msi" -File | Select-Object -First 1
        if (-not $msiFile) { Stop-Release 'The .msi was not produced.' }
        $assets.Add($msiFile.FullName)
    }

    $sums = Join-Path $dist 'SHA256SUMS.txt'
    $lines = foreach ($a in $assets) { "$((Get-FileHash -LiteralPath $a -Algorithm SHA256).Hash.ToLower())  $(Split-Path -Leaf $a)" }
    Set-Content -LiteralPath $sums -Value $lines -Encoding ASCII
    $assets.Add($sums)

    # ---------------------------------------------------------------- publish

    Write-Info 'Files to publish:'
    $assets | ForEach-Object { Write-Info ("  " + $_) }

    if ($DryRun) {
        Write-Info "Dry run: pom.xml restored, nothing committed or published. Would release $tag in $Repo as $activeUser."
        return
    }

    if (-not $Yes) {
        $kind = if ($Draft) { 'DRAFT release' } elseif ($Prerelease) { 'PRE-RELEASE' } else { 'public release' }
        $what = if ($Bump -ne 'none') { "commit 'Release $version' on main, push main and publish" } else { 'publish' }
        $answer = Read-Host "As '$activeUser' in ${Repo}: $what the $kind $tag? [y/N]"
        if ($answer -notmatch '^(y|yes|s|si)$') { Stop-Release 'Cancelled, nothing was committed or published.' }
    }

    # Dedicated version-bump commit on main, then push main with the chosen account's credentials.
    if ($Bump -ne 'none') {
        & git -C $ProjectDir add -- pom.xml
        & git -C $ProjectDir commit -m "Release $version" -m "Bump version $currentVersion -> $version."
        if ($LASTEXITCODE -ne 0) { Stop-Release 'git commit failed; pom.xml was restored.' }
        $committed = $true
    }
    $head = (& git -C $ProjectDir rev-parse HEAD | Out-String).Trim()
    # Pushing to the explicit URL (not "origin") so the gh account chosen above is the one used.
    Invoke-GitAs @('push', "https://github.com/$Repo.git", 'main:main')
    if ($LASTEXITCODE -ne 0) {
        Stop-Release "git push failed. The bump commit stays local on main; fix the access problem and push it, then re-run with -Bump none."
    }
    Test-Native { git -C $ProjectDir fetch origin main } | Out-Null   # refresh origin/main locally

    $ghArgs = @('release', 'create', $tag, '--repo', $Repo, '--target', $head, '--title', "GitGui $version")
    if ($Notes) { $ghArgs += @('--notes', $Notes) } else { $ghArgs += '--generate-notes' }
    if ($Draft) { $ghArgs += '--draft' }
    if ($Prerelease) { $ghArgs += '--prerelease' }
    $ghArgs += $assets

    $created = $false
    try {
        $url = Invoke-Gh $ghArgs
        $created = $true
    } finally {
        if (-not $created) { Write-Warn "The release was not created, but main is already pushed. Retry with: .\scripts\release.ps1 -Bump none" }
    }
    Write-Info "Release created: $url"
} finally {
    # Anything that ends before the bump commit (build failure, dry run, cancel) leaves pom.xml as committed.
    if ($Bump -ne 'none' -and -not $committed) { Restore-Pom }
}
